// Reproducible browser bundle: no CDN or npm runtime is needed inside Zotero.
import { build } from "esbuild";
import { readFile, writeFile } from "node:fs/promises";
import assert from "node:assert/strict";
const generated = await build({
	entryPoints: ["eventsource-parser"], bundle: true, format: "iife", globalName: "ZusiaEventSource",
	platform: "browser", target: "firefox115", outfile: "src/content/lib/eventsource-parser.js", write: false,
	banner: { js: "// eventsource-parser 4.1.3 (MIT). Generated by npm run vendor; see EVENTSOURCE-PARSER-LICENSE." },
});
const outputs = [
	["src/content/lib/eventsource-parser.js", generated.outputFiles[0].text],
	["src/content/lib/EVENTSOURCE-PARSER-LICENSE", await readFile("node_modules/eventsource-parser/LICENSE", "utf8")],
];
for (const [file, expected] of outputs) {
	if (process.argv.includes("--check")) {
		const normalize = text => text.replace(/\r\n/g, "\n");
		assert.equal(normalize(await readFile(file, "utf8")), normalize(expected), file + " is out of date; run npm run vendor");
	}
	else await writeFile(file, expected);
}
